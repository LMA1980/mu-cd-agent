//! Dual A/B deployment slot management and atomic symlink swapping.

#![deny(unsafe_code)]

use std::fs;
use std::os::unix::fs::symlink;
use std::path::{Path, PathBuf};
use std::sync::Arc;
use std::time::{SystemTime, UNIX_EPOCH};

use mu_cd_ipc::DeploymentSlot;

use crate::btrfs::{
    candidate_binary_names, candidate_systemd_units, is_static_web_service, validate_service_name,
    CommandRunner,
};
use crate::error::AgentError;
use crate::manifest::{DeploymentConfig, MuCdManifest};

/// Primary continuous delivery root directory on cluster nodes.
pub const PRIMARY_CD_ROOT: &str = "/srv/mucd";

/// Legacy continuous delivery root directory retained during migration.
pub const LEGACY_CD_ROOT: &str = "/srv/muconde";

/// Returns `true` when `path` matches one of the production CD roots (`/srv/mucd` or `/srv/muconde`).
pub fn is_production_cd_root(path: &Path) -> bool {
    matches!(path.to_str(), Some(PRIMARY_CD_ROOT | LEGACY_CD_ROOT))
        || path == Path::new(PRIMARY_CD_ROOT)
        || path == Path::new(LEGACY_CD_ROOT)
}

/// Resolves the default production CD root (`/srv/mucd` if present, else `/srv/muconde` if
/// present, else `/srv/mucd`).
pub fn default_cd_root() -> PathBuf {
    default_cd_root_with(|p| p.exists())
}

/// Pure helper resolving the default CD root against a caller-supplied existence predicate.
pub fn default_cd_root_with(exists: impl Fn(&Path) -> bool) -> PathBuf {
    let primary = Path::new(PRIMARY_CD_ROOT);
    if exists(primary) {
        return primary.to_path_buf();
    }
    let legacy = Path::new(LEGACY_CD_ROOT);
    if exists(legacy) {
        return legacy.to_path_buf();
    }
    primary.to_path_buf()
}

/// Deployment slot identifier.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Slot {
    A,
    B,
}

impl Slot {
    /// String representation matching Btrfs subvolume naming (@a / @b).
    pub fn as_str(&self) -> &'static str {
        match self {
            Slot::A => "@a",
            Slot::B => "@b",
        }
    }

    /// Returns the opposite deployment slot (`A <-> B`) for symmetric ping-pong alternation.
    pub const fn other(self) -> Self {
        match self {
            Slot::A => Slot::B,
            Slot::B => Slot::A,
        }
    }

    /// Resolves `@a` or `@b` (or a path ending with `/@a` or `/@b`) into a [`Slot`].
    pub fn from_target_str(target: &str) -> Option<Self> {
        let trimmed = target.trim_end_matches('/');
        if trimmed == "@a" || trimmed.ends_with("/@a") {
            Some(Slot::A)
        } else if trimmed == "@b" || trimmed.ends_with("/@b") {
            Some(Slot::B)
        } else {
            None
        }
    }
}

/// Resolves the currently active slot from `<service_dir>/current` without validating service allowlists.
pub(crate) fn read_active_slot_at(service_dir: &Path) -> Result<Option<Slot>, AgentError> {
    let link_path = service_dir.join("current");
    if !link_path.is_symlink() && !link_path.exists() {
        return Ok(None);
    }

    let target = fs::read_link(&link_path).map_err(AgentError::Io)?;
    let target_str = target.to_string_lossy();
    Slot::from_target_str(&target_str)
        .ok_or_else(|| {
            AgentError::Slot(format!(
                "Symlink {} points to unrecognized target: {}",
                link_path.display(),
                target_str
            ))
        })
        .map(Some)
}

impl From<DeploymentSlot> for Slot {
    fn from(slot: DeploymentSlot) -> Self {
        match slot {
            DeploymentSlot::SlotA => Slot::A,
            DeploymentSlot::SlotB => Slot::B,
        }
    }
}

impl From<Slot> for DeploymentSlot {
    fn from(slot: Slot) -> Self {
        match slot {
            Slot::A => DeploymentSlot::SlotA,
            Slot::B => DeploymentSlot::SlotB,
        }
    }
}

/// Verification receipt generated upon atomic slot pointer swap.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SwapReceipt {
    pub service: String,
    pub active_slot: Slot,
    pub swapped_at_epoch_ms: u64,
}

/// Receipt generated by [`SlotManager::atomic_swap_active_slot_for_self_upgrade`], carrying
/// the installed binary path (for pre-restart `--version` validation) and resolved systemd unit.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SelfUpgradeSwapReceipt {
    pub receipt: SwapReceipt,
    pub installed_binary_path: Option<PathBuf>,
    pub resolved_unit: String,
}

/// Manager responsible for atomic slot pointer swapping and systemd restarts.
pub struct SlotManager {
    root_dir: PathBuf,
    runner: Arc<dyn CommandRunner>,
}

impl SlotManager {
    pub fn new(root_dir: impl Into<PathBuf>, runner: Arc<dyn CommandRunner>) -> Self {
        Self {
            root_dir: root_dir.into(),
            runner,
        }
    }

    pub fn root_dir(&self) -> &Path {
        &self.root_dir
    }

    pub fn service_dir(&self, service: &str) -> PathBuf {
        self.root_dir.join(service)
    }

    pub fn current_symlink(&self, service: &str) -> PathBuf {
        self.service_dir(service).join("current")
    }

    /// Reads the currently active slot for the service by inspecting the `current` symlink.
    pub fn read_active_slot(&self, service: &str) -> Result<Option<Slot>, AgentError> {
        validate_service_name(service)?;
        read_active_slot_at(&self.service_dir(service))
    }

    /// Resolves the candidate target slot for the next deployment: `active.other()` when
    /// `<svc>/current` is set, or [`Slot::B`] on an uninitialized bootstrap layout.
    pub fn resolve_target_slot(&self, service: &str) -> Result<Slot, AgentError> {
        Ok(self
            .read_active_slot(service)?
            .map(Slot::other)
            .unwrap_or(Slot::B))
    }

    /// Rolls back atomically to `preferred_restore` (or the opposite of `<svc>/current`),
    /// restoring the target slot from its latest read-only Btrfs snapshot if missing.
    pub fn rollback_to_prior_slot(
        &self,
        service: &str,
        preferred_restore: Option<Slot>,
    ) -> Result<SwapReceipt, AgentError> {
        self.rollback_to_prior_slot_with_deployment(service, preferred_restore, None, None)
    }

    /// Rolls back atomically to `preferred_restore` while honoring declarative [`DeploymentConfig`]
    /// overrides (suppressing `systemctl restart` for static web bundles and resolving canonical
    /// systemd unit aliases for daemons).
    ///
    /// When `deployment` is `None`, attempts to load `.mucd/mu-cd.yml` (or legacy
    /// `.muconde/MuConDe.yml`) from `<svc>/<restore_slot>`, `<svc>`, or the root directory.
    pub fn rollback_to_prior_slot_with_deployment(
        &self,
        service: &str,
        preferred_restore: Option<Slot>,
        deployment: Option<&DeploymentConfig>,
        cmd_systemd_unit: Option<&str>,
    ) -> Result<SwapReceipt, AgentError> {
        validate_service_name(service)?;
        let restore_slot = match preferred_restore {
            Some(slot) => slot,
            None => self
                .read_active_slot(service)?
                .map(Slot::other)
                .unwrap_or(Slot::A),
        };

        let srv_dir = self.service_dir(service);
        let slot_dir = srv_dir.join(restore_slot.as_str());
        if !slot_dir.exists() {
            crate::btrfs::restore_slot_from_latest_snapshot_if_available(
                &srv_dir,
                restore_slot,
                self.runner.as_ref(),
            )?;
        }

        let resolved_manifest = if deployment.is_none() {
            load_deployment_from_dirs(&[&slot_dir, &srv_dir, &self.root_dir])?
        } else {
            None
        };
        let effective_deployment = deployment.or(resolved_manifest.as_ref());

        self.atomic_swap_active_slot_with_deployment(
            service,
            restore_slot,
            effective_deployment,
            cmd_systemd_unit,
        )
    }

    /// Restores `restore_slot` from the newest read-only snapshot of that slot (or latest
    /// available snapshot) and atomically switches `<svc>/current` to `restore_slot`.
    pub fn rollback_restoring_snapshot(
        &self,
        service: &str,
        restore_slot: Slot,
    ) -> Result<SwapReceipt, AgentError> {
        validate_service_name(service)?;
        let srv_dir = self.service_dir(service);
        let slot_dir = srv_dir.join(restore_slot.as_str());
        crate::btrfs::restore_slot_from_latest_snapshot(
            &srv_dir,
            restore_slot,
            self.runner.as_ref(),
        )?;
        let resolved_manifest = load_deployment_from_dirs(&[&slot_dir, &srv_dir, &self.root_dir])?;
        self.atomic_swap_active_slot_with_deployment(
            service,
            restore_slot,
            resolved_manifest.as_ref(),
            None,
        )
    }

    /// Atomically swaps the active slot pointer (`/srv/mucd/<service>/current` or legacy `/srv/muconde/<service>/current`):
    /// 1. Creates a temporary symlink `.current.tmp.<nonce>` pointing to `@a` or `@b`.
    /// 2. Atomically replaces `current` via `std::fs::rename` (POSIX rename(2) atomicity).
    /// 3. Triggers `systemctl restart <service>` and returns a `SwapReceipt`.
    pub fn atomic_swap_active_slot(
        &self,
        service: &str,
        target_slot: Slot,
    ) -> Result<SwapReceipt, AgentError> {
        self.atomic_swap_active_slot_with_deployment(service, target_slot, None, None)
    }

    /// Atomically swaps the active slot pointer while applying optional manifest [`DeploymentConfig`]
    /// and IPC `systemd_unit` overrides:
    /// - Static web services copy `dist/` to `web_root`, optionally reload `nginx.service` if
    ///   active, and **never** execute `systemctl restart <service>`.
    /// - Daemon services resolve canonical/aliased systemd units and install staged binaries to
    ///   `install_path` (or `/usr/local/bin/<canonical_binary>`).
    pub fn atomic_swap_active_slot_with_deployment(
        &self,
        service: &str,
        target_slot: Slot,
        deployment: Option<&DeploymentConfig>,
        cmd_systemd_unit: Option<&str>,
    ) -> Result<SwapReceipt, AgentError> {
        validate_service_name(service)?;

        let srv_dir = self.service_dir(service);
        fs::create_dir_all(&srv_dir)?;

        let nonce = uuid::Uuid::new_v4().simple().to_string();
        let tmp_symlink = srv_dir.join(format!(".current.tmp.{}", nonce));
        let current_symlink = srv_dir.join("current");

        // 1. Create temporary symlink pointing to target subvolume relative name (@a or @b)
        symlink(target_slot.as_str(), &tmp_symlink).map_err(AgentError::Io)?;

        // 2. Atomically replace current via POSIX rename(2)
        if let Err(e) = fs::rename(&tmp_symlink, &current_symlink) {
            let _ = fs::remove_file(&tmp_symlink);
            return Err(AgentError::Io(e));
        }

        // 3. On production root (/srv/mucd or /srv/muconde), activate static web bundle or binary before restart
        let is_prod = is_production_cd_root(&self.root_dir);
        if is_prod {
            let slot_dir = srv_dir.join(target_slot.as_str());
            if is_static_web_service(service) {
                let web_root = resolve_web_root(service, deployment)?;
                let dist_dir = slot_dir.join("dist");
                if !dist_dir.is_dir() {
                    return Err(AgentError::Slot(format!(
                        "Staged static web bundle directory '{}' is missing",
                        dist_dir.display()
                    )));
                }
                fs::create_dir_all(&web_root)?;
                let src_dot = format!("{}/.", dist_dir.display());
                self.runner
                    .run_command("cp", &["-a", &src_dot, &web_root])?;
            } else if let Some(staged_bin) = find_staged_binary(&slot_dir, service, deployment) {
                let meta = fs::metadata(&staged_bin)?;
                if meta.len() > 0 {
                    if let Some(dest_bin) = resolve_install_binary_path(service, deployment)? {
                        let staged_str = staged_bin.to_str().ok_or_else(|| {
                            AgentError::Slot(format!(
                                "Non-UTF-8 staged binary path: '{}'",
                                staged_bin.display()
                            ))
                        })?;
                        self.runner
                            .run_command("install", &["-m", "755", staged_str, &dest_bin])?;
                    }
                }
            }
        }

        // 4. Restart daemon systemd unit (static web services reload nginx only if active, never systemctl restart <service>)
        if is_static_web_service(service) {
            if is_prod {
                if let Ok(out) = self
                    .runner
                    .run_command("systemctl", &["is-active", "--quiet", "nginx.service"])
                {
                    if out.status == 0 {
                        self.runner
                            .run_command("systemctl", &["reload", "nginx.service"])?;
                    }
                }
            }
        } else if !(is_prod && matches!(service, "muconde-agent" | "mu-cd-agent")) {
            let restart_target =
                self.resolve_systemd_restart_target(service, deployment, cmd_systemd_unit)?;
            self.runner
                .run_command("systemctl", &["restart", &restart_target])?;
        }

        let swapped_at_epoch_ms = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .map(|d| d.as_millis() as u64)
            .unwrap_or(0);

        tracing::info!(
            service = service,
            slot = target_slot.as_str(),
            swapped_at = swapped_at_epoch_ms,
            "Successfully executed atomic slot swap"
        );

        Ok(SwapReceipt {
            service: service.to_string(),
            active_slot: target_slot,
            swapped_at_epoch_ms,
        })
    }

    /// Atomically swaps the Btrfs `current` symlink and installs the staged binary (`install -m 755`
    /// on production roots) **without** immediately calling `systemctl restart`, allowing the agent
    /// to validate `<installed_bin> --version` and persist a detached self-upgrade handoff first.
    pub fn atomic_swap_active_slot_for_self_upgrade(
        &self,
        service: &str,
        target_slot: Slot,
        deployment: Option<&DeploymentConfig>,
        cmd_systemd_unit: Option<&str>,
    ) -> Result<SelfUpgradeSwapReceipt, AgentError> {
        validate_service_name(service)?;

        let srv_dir = self.service_dir(service);
        fs::create_dir_all(&srv_dir)?;

        let nonce = uuid::Uuid::new_v4().simple().to_string();
        let tmp_symlink = srv_dir.join(format!(".current.tmp.{nonce}"));
        let current_symlink = srv_dir.join("current");

        symlink(target_slot.as_str(), &tmp_symlink).map_err(AgentError::Io)?;
        if let Err(e) = fs::rename(&tmp_symlink, &current_symlink) {
            let _ = fs::remove_file(&tmp_symlink);
            return Err(AgentError::Io(e));
        }

        let slot_dir = srv_dir.join(target_slot.as_str());
        let is_prod = is_production_cd_root(&self.root_dir);
        let mut installed_binary_path = None;

        if let Some(staged_bin) = find_staged_binary(&slot_dir, service, deployment) {
            if is_prod {
                let meta = fs::metadata(&staged_bin)?;
                if meta.len() > 0 {
                    if let Some(dest_bin) = resolve_install_binary_path(service, deployment)? {
                        let staged_str = staged_bin.to_str().ok_or_else(|| {
                            AgentError::Slot(format!(
                                "Non-UTF-8 staged binary path: '{}'",
                                staged_bin.display()
                            ))
                        })?;
                        self.runner
                            .run_command("install", &["-m", "755", staged_str, &dest_bin])?;
                        installed_binary_path = Some(PathBuf::from(dest_bin));
                    }
                }
            } else {
                installed_binary_path = Some(staged_bin);
            }
        }

        let resolved_unit =
            self.resolve_systemd_restart_target(service, deployment, cmd_systemd_unit)?;
        let swapped_at_epoch_ms = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .map(|d| d.as_millis() as u64)
            .unwrap_or(0);

        tracing::info!(
            service = service,
            slot = target_slot.as_str(),
            resolved_unit = %resolved_unit,
            swapped_at = swapped_at_epoch_ms,
            "Executed self-upgrade slot swap and binary installation (restart deferred)"
        );

        Ok(SelfUpgradeSwapReceipt {
            receipt: SwapReceipt {
                service: service.to_string(),
                active_slot: target_slot,
                swapped_at_epoch_ms,
            },
            installed_binary_path,
            resolved_unit,
        })
    }

    /// Atomically restores `restore_slot` symlink and binary without calling `systemctl restart`.
    pub fn restore_slot_without_restart(
        &self,
        service: &str,
        restore_slot: Slot,
        deployment: Option<&DeploymentConfig>,
        cmd_systemd_unit: Option<&str>,
    ) -> Result<SelfUpgradeSwapReceipt, AgentError> {
        validate_service_name(service)?;
        let srv_dir = self.service_dir(service);
        let slot_dir = srv_dir.join(restore_slot.as_str());
        if !slot_dir.exists() {
            crate::btrfs::restore_slot_from_latest_snapshot_if_available(
                &srv_dir,
                restore_slot,
                self.runner.as_ref(),
            )?;
        }
        let resolved_manifest = if deployment.is_none() {
            load_deployment_from_dirs(&[&slot_dir, &srv_dir, &self.root_dir])?
        } else {
            None
        };
        let effective_deployment = deployment.or(resolved_manifest.as_ref());
        self.atomic_swap_active_slot_for_self_upgrade(
            service,
            restore_slot,
            effective_deployment,
            cmd_systemd_unit,
        )
    }

    /// Triggers a detached `systemctl restart --no-block <unit>` for self-upgrade handoff.
    pub fn run_systemctl_restart_no_block(&self, unit: &str) -> Result<(), AgentError> {
        validate_unit_name(unit)?;
        self.runner
            .run_command("systemctl", &["restart", "--no-block", unit])?;
        Ok(())
    }

    pub fn resolve_systemd_restart_target(
        &self,
        service: &str,
        deployment: Option<&DeploymentConfig>,
        cmd_systemd_unit: Option<&str>,
    ) -> Result<String, AgentError> {
        let manifest_unit = deployment.and_then(|d| d.normalized_systemd_unit());
        let cmd_unit = normalize_unit_name(cmd_systemd_unit);

        if let Some(ref u) = manifest_unit {
            validate_unit_name(u)?;
        }
        if let Some(ref u) = cmd_unit {
            validate_unit_name(u)?;
        }

        let mut candidates = Vec::new();
        if let Some(ref u) = manifest_unit {
            candidates.push(u.clone());
        }
        for unit in candidate_systemd_units(service) {
            if !candidates.contains(&unit) {
                candidates.push(unit);
            }
        }
        if let Some(ref u) = cmd_unit {
            if !candidates.contains(u) {
                candidates.push(u.clone());
            }
        }

        if is_production_cd_root(&self.root_dir) || deployment.is_some() || cmd_unit.is_some() {
            if let Some(found) = select_installed_systemd_unit(self.runner.as_ref(), &candidates) {
                return Ok(found);
            }
        }

        if let Some(u) = manifest_unit {
            return Ok(u);
        }
        if let Some(u) = cmd_unit {
            return Ok(u);
        }
        if !is_production_cd_root(&self.root_dir) {
            return Ok(service.to_string());
        }
        Ok(candidates
            .into_iter()
            .next()
            .unwrap_or_else(|| format!("{service}.service")))
    }
}

fn load_deployment_from_dirs(dirs: &[&Path]) -> Result<Option<DeploymentConfig>, AgentError> {
    for dir in dirs {
        if let Some(manifest) = MuCdManifest::load_optional_from_dir(dir)? {
            return Ok(Some(manifest.deployment));
        }
    }
    Ok(None)
}

fn normalize_unit_name(raw: Option<&str>) -> Option<String> {
    let trimmed = raw.map(str::trim).filter(|s| !s.is_empty())?;
    if trimmed.contains('.') {
        Some(trimmed.to_string())
    } else {
        Some(format!("{trimmed}.service"))
    }
}

fn validate_unit_name(unit: &str) -> Result<(), AgentError> {
    if unit.is_empty()
        || unit.contains("..")
        || unit.contains('/')
        || unit.contains('\\')
        || !unit
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'-' | b'_' | b'.' | b'@'))
    {
        return Err(AgentError::InvalidServiceName(format!(
            "Unsafe systemd unit name '{unit}'"
        )));
    }
    Ok(())
}

/// Resolves the destination Nginx web root for a static web service.
pub fn resolve_web_root(
    service: &str,
    deployment: Option<&DeploymentConfig>,
) -> Result<String, AgentError> {
    resolve_web_root_with(service, deployment, |p| p.exists())
}

/// Pure helper resolving `web_root` against a caller-supplied path-existence predicate.
pub(crate) fn resolve_web_root_with(
    service: &str,
    deployment: Option<&DeploymentConfig>,
    exists: impl Fn(&Path) -> bool,
) -> Result<String, AgentError> {
    if let Some(raw) = deployment.and_then(|d| d.normalized_web_root()) {
        if raw.contains("..")
            || raw.contains('\\')
            || (!raw.starts_with("/var/www/") && !raw.starts_with("/srv/www/"))
        {
            return Err(AgentError::PathTraversal(format!(
                "Refusing unsafe static web_root '{raw}' (must live under /var/www/ or /srv/www/)"
            )));
        }
        return Ok(raw.to_string());
    }

    let default = match service {
        "mu-console" => {
            if exists(Path::new("/var/www/mu-console")) || !exists(Path::new("/var/www/muconsole"))
            {
                "/var/www/mu-console"
            } else {
                "/var/www/muconsole"
            }
        }
        "muconsole" => {
            if exists(Path::new("/var/www/muconsole")) || !exists(Path::new("/var/www/mu-console"))
            {
                "/var/www/muconsole"
            } else {
                "/var/www/mu-console"
            }
        }
        "mu-ci-web" => "/var/www/mu-ci-web",
        "action-runner-web" => "/var/www/action-runner-web",
        other => {
            return Err(AgentError::Slot(format!(
                "No default web_root mapped for static web service '{other}'"
            )))
        }
    };
    Ok(default.to_string())
}

/// Resolves the host destination binary path under `/usr/local/bin/` (or validated `install_path`).
pub fn resolve_install_binary_path(
    service: &str,
    deployment: Option<&DeploymentConfig>,
) -> Result<Option<String>, AgentError> {
    if let Some(raw) = deployment.and_then(|d| d.normalized_install_path()) {
        if raw.contains("..")
            || raw.contains('\\')
            || (!raw.starts_with("/usr/local/bin/") && !raw.starts_with("/usr/bin/"))
        {
            return Err(AgentError::PathTraversal(format!(
                "Refusing unsafe install_path '{raw}' (must live under /usr/local/bin/ or /usr/bin/)"
            )));
        }
        return Ok(Some(raw.to_string()));
    }
    if let Some(bin) = deployment.and_then(|d| d.normalized_binary()) {
        if bin.contains('/') || bin.contains('\\') || bin.contains("..") {
            return Err(AgentError::PathTraversal(bin.to_string()));
        }
        return Ok(Some(format!("/usr/local/bin/{bin}")));
    }
    Ok(candidate_binary_names(service)
        .first()
        .map(|bin_name| format!("/usr/local/bin/{bin_name}")))
}

fn find_staged_binary(
    slot_dir: &Path,
    service: &str,
    deployment: Option<&DeploymentConfig>,
) -> Option<PathBuf> {
    let bin_dir = slot_dir.join("bin");
    let mut names: Vec<&str> = vec![service];
    if let Some(bin) = deployment.and_then(|d| d.normalized_binary()) {
        if !names.contains(&bin) {
            names.push(bin);
        }
    }
    for alias in candidate_binary_names(service) {
        if !names.contains(alias) {
            names.push(alias);
        }
    }
    names
        .into_iter()
        .map(|n| bin_dir.join(n))
        .find(|p| p.is_file())
}

/// Selects the first installed systemd unit from ordered `candidates` using `systemctl`.
pub fn select_installed_systemd_unit(
    runner: &dyn CommandRunner,
    candidates: &[String],
) -> Option<String> {
    for unit in candidates {
        if let Ok(out) = runner.run_command("systemctl", &["list-unit-files", unit]) {
            if out.status == 0
                && out
                    .stdout
                    .lines()
                    .any(|line| line.split_whitespace().next() == Some(unit.as_str()))
            {
                return Some(unit.clone());
            }
        }
        if let Ok(out) = runner.run_command("systemctl", &["cat", unit]) {
            if out.status == 0 && !out.stdout.trim().is_empty() {
                return Some(unit.clone());
            }
        }
    }
    None
}

