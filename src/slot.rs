    #[test]
    #[cfg_attr(miri, ignore)]
    fn test_atomic_swap_active_slot_for_self_upgrade_defers_restart_and_restores() {
        let dir = tempdir().unwrap();
        let root = dir.path();
        let service = "mu-cd-agent";
        let srv_dir = root.join(service);
        fs::create_dir_all(srv_dir.join("@a/bin")).unwrap();
        fs::create_dir_all(srv_dir.join("@b/bin")).unwrap();
        fs::write(srv_dir.join("@a/bin/mu-cd-agent"), b"old-agent-bin").unwrap();
        fs::write(srv_dir.join("@b/bin/mu-cd-agent"), b"new-agent-bin").unwrap();
        symlink("@a", srv_dir.join("current")).unwrap();

        let runner = Arc::new(MockCommandRunner::new(true));
        let mgr = SlotManager::new(root, runner.clone());

        let swap = mgr
            .atomic_swap_active_slot_for_self_upgrade(
                service,
                Slot::B,
                None,
                Some("muconde-agent.service"),
            )
            .expect("self-upgrade swap succeeds without restart");
        assert_eq!(swap.receipt.active_slot, Slot::B);
        assert_eq!(
            swap.installed_binary_path.as_deref(),
            Some(srv_dir.join("@b/bin/mu-cd-agent").as_path())
        );
        assert_eq!(mgr.read_active_slot(service).unwrap(), Some(Slot::B));
        assert!(
            !runner
                .recorded_calls()
                .iter()
                .map(|c| c.join(" "))
                .any(|c| c.contains("systemctl restart")),
            "self-upgrade swap must not invoke systemctl restart directly"
        );

        let restored = mgr
            .restore_slot_without_restart(service, Slot::A, None, Some("muconde-agent.service"))
            .expect("restore without restart succeeds");
        assert_eq!(restored.receipt.active_slot, Slot::A);
        assert_eq!(mgr.read_active_slot(service).unwrap(), Some(Slot::A));
        assert!(
            !runner
                .recorded_calls()
                .iter()
                .map(|c| c.join(" "))
                .any(|c| c.contains("systemctl restart")),
            "restore_slot_without_restart must not call systemctl restart"
        );

        mgr.run_systemctl_restart_no_block(&swap.resolved_unit)
            .expect("detached restart succeeds");
        assert!(runner
            .recorded_calls()
            .iter()
            .map(|c| c.join(" "))
            .any(|c| c.starts_with("systemctl restart --no-block ")));
    }
