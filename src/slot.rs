    #[test]
    #[cfg_attr(miri, ignore)]
    fn test_resolve_target_slot_and_symmetric_rollback() {
        let temp = tempdir().unwrap();
        let root = temp.path().join("muconde");
        let service = "mu-cd-agent";
        let srv_dir = root.join(service);
        fs::create_dir_all(srv_dir.join("@a")).unwrap();
        fs::create_dir_all(srv_dir.join("@b")).unwrap();

        let runner = Arc::new(MockCommandRunner::new(true));
        let manager = SlotManager::new(&root, runner);

        // Uninitialized symlink defaults candidate to Slot::B
        assert_eq!(manager.resolve_target_slot(service).unwrap(), Slot::B);

        // Active @a -> candidate @b
        manager.atomic_swap_active_slot(service, Slot::A).unwrap();
        assert_eq!(manager.resolve_target_slot(service).unwrap(), Slot::B);

        // Active @b -> candidate @a; inferred rollback restores @a
        manager.atomic_swap_active_slot(service, Slot::B).unwrap();
        assert_eq!(manager.resolve_target_slot(service).unwrap(), Slot::A);
        let rb_to_a = manager.rollback_to_prior_slot(service, None).unwrap();
        assert_eq!(rb_to_a.active_slot, Slot::A);
        assert_eq!(manager.read_active_slot(service).unwrap(), Some(Slot::A));

        // Now swap @b -> @a leg: active is @a, rollback to explicit @b
        let rb_to_b = manager
            .rollback_to_prior_slot(service, Some(Slot::B))
            .unwrap();
        assert_eq!(rb_to_b.active_slot, Slot::B);
        assert_eq!(manager.read_active_slot(service).unwrap(), Some(Slot::B));
    }

    #[test]
    #[cfg_attr(miri, ignore)]
    fn test_static_web_swap_suppresses_systemctl_restart_and_resolves_canonical_units() {
        let temp = tempdir().unwrap();
        let root = temp.path().join("muconde");
        let runner = Arc::new(MockCommandRunner::new(true));
        let manager = SlotManager::new(&root, runner.clone());

        fs::create_dir_all(root.join("mu-console/@a/dist")).unwrap();
        fs::write(
            root.join("mu-console/@a/dist/index.html"),
            b"<html>ok</html>",
        )
        .unwrap();
        let receipt = manager
            .atomic_swap_active_slot("mu-console", Slot::A)
            .expect("static web swap should succeed");
        assert_eq!(receipt.active_slot, Slot::A);
        assert!(
            !runner
                .recorded_calls()
                .iter()
                .any(|c| c.contains(&"restart".to_string())),
            "Static web swap must never call systemctl restart"
        );

        // Daemon systemd alias discovery picks installed alias over stale legacy command name
        runner.set_command_output(
            "systemctl list-unit-files mu-registry.service",
            crate::btrfs::CommandOutput {
                status: 0,
                stdout: "mu-registry.service enabled enabled\n\n1 unit files listed.\n".into(),
                stderr: String::new(),
            },
        );
        fs::create_dir_all(root.join("muregist/@b")).unwrap();
        manager
            .atomic_swap_active_slot_with_deployment(
                "muregist",
                Slot::B,
                None,
                Some("muregist.service"),
            )
            .unwrap();
        let restart_call = runner
            .recorded_calls()
            .into_iter()
            .find(|c| c.len() >= 3 && c[0] == "systemctl" && c[1] == "restart")
            .unwrap();
        assert_eq!(
            restart_call,
            vec!["systemctl", "restart", "mu-registry.service"]
        );

        // Manifest deployment override wins cleanly
        let dep = DeploymentConfig {
            install_path: Some("/usr/local/bin/mu-observable-sentinel".into()),
            systemd_unit: Some("mu-observable-sentinel.service".into()),
            web_root: Some("/var/www/muconsole".into()),
            ..Default::default()
        };
        assert_eq!(
            resolve_install_binary_path("muobserve-sentinel", Some(&dep))
                .unwrap()
                .as_deref(),
            Some("/usr/local/bin/mu-observable-sentinel")
        );
        assert_eq!(
            resolve_web_root("mu-console", Some(&dep)).unwrap(),
            "/var/www/muconsole"
        );
        // Unsafe path traversal in deployment config fails closed
        let unsafe_dep = DeploymentConfig {
            web_root: Some("/etc/nginx".into()),
            ..Default::default()
        };
        assert!(matches!(
            resolve_web_root("mu-console", Some(&unsafe_dep)),
            Err(AgentError::PathTraversal(_))
        ));

        // Rollback without explicit deployment falls back to manifest in restore slot dir
        let svc_dir = root.join("mu-cd-controller");
        fs::create_dir_all(svc_dir.join("@a/.mucd")).unwrap();
        fs::create_dir_all(svc_dir.join("@b")).unwrap();
        fs::write(
            svc_dir.join("@a/.mucd/mu-cd.yml"),
            "deployment:\n  systemd_unit: custom-controller-restore.service\n",
        )
        .unwrap();
        let rb_runner = Arc::new(MockCommandRunner::new(true));
        let rb_mgr = SlotManager::new(&root, rb_runner.clone());
        rb_mgr
            .rollback_to_prior_slot("mu-cd-controller", Some(Slot::A))
            .unwrap();
        let rb_restart = rb_runner
            .recorded_calls()
            .into_iter()
            .find(|c| c.len() >= 3 && c[0] == "systemctl" && c[1] == "restart")
            .unwrap();
        assert_eq!(
            rb_restart,
            vec![
                "systemctl".to_string(),
                "restart".to_string(),
                "custom-controller-restore.service".to_string()
            ]
        );
    }

